#!/usr/bin/env python3
"""Compile the five phenotype kernels to SPIR-V and write them as C arrays (guest/anny_fit/pheno_spv.h).
The .slang are the Lean emitter's output (sinew-mocap/solve core/spec: `lake exe emit_shaders slang`); scalar layout makes float3 12 bytes
in a StructuredBuffer, as on the CPU; precise rounds in the same order as -ffp-contract=off.
    python3 tools/embed_spv.py assets guest/anny_fit/pheno_spv.h
"""
import subprocess, sys, tempfile, os
src, out = sys.argv[1:3]
KERNELS = ["blendshape", "bary_tet", "bary_gather", "rbf", "skeleton_fit"]
lines = ["// Generated by tools/embed_spv.py from the Lean-emitted pheno_*.slang. Do not edit.", "#pragma once", "#include <cstddef>", "#include <cstdint>", ""]
for k in KERNELS:
    spv = os.path.join(tempfile.mkdtemp(), k + ".spv")
    subprocess.run(["slangc", os.path.join(src, f"pheno_{k}.slang"), "-entry", k, "-stage", "compute", "-target", "spirv", "-force-glsl-scalar-layout", "-fp-mode", "precise", "-o", spv], check=True)
    b = open(spv, "rb").read()
    lines.append(f"static const uint8_t pheno_{k}_spv[{len(b)}] = {{")
    for i in range(0, len(b), 16):
        lines.append("\t" + ", ".join(str(x) for x in b[i:i + 16]) + ",")
    lines.append("};")
lines.append("")
open(out, "w").write("\n".join(lines))
print("wrote", out)
